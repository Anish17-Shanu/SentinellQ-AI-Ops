#!/usr/bin/env python3
"""Prepare the static dashboard for the Vercel serverless target.

Vercel serves static files from ``public/`` and Python functions from ``api/``.
This script copies the dashboard into ``public/dashboard`` and points it at the
``/api`` prefix that the ASGI entrypoint receives.

Run automatically by ``vercel.json`` (buildCommand) or manually:
    python scripts/prepare_vercel.py
"""

from __future__ import annotations

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DASHBOARD = ROOT / "dashboard"
PUBLIC = ROOT / "public"

REDIRECT_PAGE = """<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <meta http-equiv="refresh" content="0; url=/dashboard/" />
    <title>SentinelIQ AI Ops</title>
  </head>
  <body>
    <p>Redirecting to the <a href="/dashboard/">SentinelIQ dashboard</a>.</p>
  </body>
</html>
"""


def main() -> int:
    if not (DASHBOARD / "index.html").exists():
        print(f"error: dashboard not found at {DASHBOARD}", file=sys.stderr)
        return 2

    if PUBLIC.exists():
        shutil.rmtree(PUBLIC)
    target = PUBLIC / "dashboard"
    shutil.copytree(DASHBOARD, target)

    (target / "config.js").write_text(
        "// Generated by scripts/prepare_vercel.py for the Vercel serverless target.\n"
        'window.SENTINELIQ_API_BASE = "/api";\n',
        encoding="utf-8",
    )
    (PUBLIC / "index.html").write_text(REDIRECT_PAGE, encoding="utf-8")

    files = sorted(path.relative_to(PUBLIC).as_posix() for path in PUBLIC.rglob("*") if path.is_file())
    print(f"Prepared {len(files)} static file(s) in {PUBLIC}:")
    for name in files:
        print(f"  {name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
